/**
 * Bundles eval results for the in-app test report (public/report/) and
 * writes docs/EVAL.md. Uses only cached answers: no API calls.
 * Usage: node --experimental-strip-types eval/publish.ts
 */
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fromModel, type ModelReading, type Reading } from '../src/read/schema.ts';

/** Models shown in the report, in order. The first is the app's main reader. */
const MODELS = (process.env.REPORT_MODELS ?? 'gemini-3-flash-preview@low,gemini-3.5-flash@low,gemini-3.8-flash@low,gemini-3.5-flash-lite,gemini-3.1-flash-lite').split(',');
const root = new URL('../', import.meta.url);
const outDir = new URL('public/report/', root);
mkdirSync(new URL('cases/', outDir), { recursive: true });

interface Row {
  id: string;
  title: string;
  tests: string;
  split: string;
  hard: boolean;
  physics: boolean;
  ms: number;
  error: string;
  score: { pass: boolean; reasons: string[]; positionError: number | null; outcome: { ok: boolean } };
  scoreRaw: { pass: boolean; reasons: string[] };
}

const index = JSON.parse(readFileSync(new URL('eval/cases/index.json', root), 'utf8')) as { id: string }[];
const models: { model: string; summary: unknown; rows: Row[] }[] = [];
for (const model of MODELS) {
  let f = new URL(`eval/results/${model}.json`, root);
  if (!existsSync(f)) f = new URL(`eval/results/${model}-dev.json`, root);
  if (!existsSync(f)) continue;
  const { summary, rows } = JSON.parse(readFileSync(f, 'utf8')) as { summary: unknown; rows: Row[] };
  models.push({ model, summary, rows });
}

const cases = index.map(({ id }) => {
  const t = JSON.parse(readFileSync(new URL(`eval/cases/${id}.truth.json`, root), 'utf8')) as { width: number; height: number; truth: Reading; title: string; tests: string; split: string; hard: boolean; physics: boolean };
  copyFileSync(new URL(`eval/cases/${id}.jpg`, root), new URL(`cases/${id}.jpg`, outDir));
  const reads: Record<string, Reading | null> = {};
  for (const { model } of models) {
    const f = new URL(`eval/out/${model}/${id}.json`, root);
    reads[model] = existsSync(f) ? fromModel((JSON.parse(readFileSync(f, 'utf8')) as { raw: ModelReading }).raw) : null;
  }
  return { id, title: t.title, tests: t.tests, split: t.split, hard: t.hard, physics: t.physics, width: t.width, height: t.height, truth: t.truth, reads };
});

writeFileSync(new URL('data.json', outDir), JSON.stringify({ generated: new Date().toISOString().slice(0, 10), models, cases }));

// ---- docs/EVAL.md ----
const lines: string[] = [];
lines.push('# How the drawing reader was tested', '');
lines.push('Generated by `eval/publish.ts` from the cached answers in `eval/out/`. Re-run with `npm run eval -- --model <model>`.', '');
lines.push('| Model | Cases | Pass (AI + snap) | Pass (AI alone) | Objects found | Invented | Labels | Links | Same outcome | Mean position error (/1000) | Median time |');
lines.push('| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |');
for (const m of models) {
  const done = m.rows.filter((r) => !r.error);
  const sum = (f: (r: Row & { score: Record<string, unknown> }) => number) => done.reduce((s, r) => s + f(r as never), 0);
  const sc = (r: Row) => r.score as unknown as { objects: { found: number; expected: number; extra: number }; labels: { correct: number; expected: number }; links: { correct: number; expected: number }; outcome: { ok: boolean }; positionError: number | null };
  const phys = done.filter((r) => r.physics);
  const pos = phys.map((r) => sc(r).positionError).filter((x): x is number => x !== null);
  const ms = [...done.map((r) => r.ms)].sort((a, b) => a - b);
  lines.push(
    `| ${m.model} | ${done.length}${m.rows.length > done.length ? ` (+${m.rows.length - done.length} no answer)` : ''} | ${done.filter((r) => r.score.pass).length} | ${done.filter((r) => r.scoreRaw.pass).length} | ${sum((r) => sc(r).objects.found)}/${sum((r) => sc(r).objects.expected)} | ${sum((r) => sc(r).objects.extra)} | ${sum((r) => sc(r).labels.correct)}/${sum((r) => sc(r).labels.expected)} | ${sum((r) => sc(r).links.correct)}/${sum((r) => sc(r).links.expected)} | ${phys.filter((r) => sc(r).outcome.ok).length}/${phys.length} | ${pos.length ? (pos.reduce((a, b) => a + b, 0) / pos.length).toFixed(1) : '–'} | ${ms.length ? (ms[Math.floor(ms.length / 2)]! / 1000).toFixed(1) : '–'} s |`,
  );
}
lines.push('');
for (const m of models) {
  const fails = m.rows.filter((r) => !r.error && !r.score.pass);
  if (!fails.length) continue;
  lines.push(`## Failures: ${m.model}`, '');
  for (const r of fails) lines.push(`- **${r.id}** (${r.tests}${r.hard ? ', hard case' : ''}): ${r.score.reasons.join('; ')}`);
  lines.push('');
}
mkdirSync(new URL('docs/', root), { recursive: true });
writeFileSync(new URL('docs/EVAL.md', root), lines.join('\n'));
console.log(lines.slice(0, 4 + models.length).join('\n'));
console.log(`cases ${cases.length}, models ${models.map((m) => `${m.model}:${m.rows.length}`).join(' ')}; images ${readdirSync(new URL('cases/', outDir)).length}`);
